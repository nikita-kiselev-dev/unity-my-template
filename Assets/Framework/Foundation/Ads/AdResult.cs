namespace Framework.Foundation.Ads
{
    public enum AdResult
    {
        /// Реклама досмотрена: только этот исход считается просмотром и даёт награду.
        Success,

        /// Игрок закрыл рекламу сам.
        Skipped,

        /// Показывать нечего: формат выключен, кулдаун не истёк, сеть не готова или идёт другой показ.
        NotReady,

        /// Сеть или заглушка сообщили об ошибке показа.
        Failed
    }
}
