namespace Framework.Foundation.Initialization
{
    /// Условие, которое нельзя выразить флагом конфига: сущность сама решает, нужна ли она в этом
    /// запуске. `ShouldRun` вызывается один раз до фаз — если он вернул false, ни одна фаза не
    /// выполняется ни для сущности, ни для её обёрток (ассеты не грузятся, view не создаётся).
    /// Всё, что нужно для решения, к этому моменту готово: config, серверное время, сейв.
    public interface IConditionalEntity
    {
        bool ShouldRun();
    }
}
