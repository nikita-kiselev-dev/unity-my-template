        [Test]
        public void Generator_ReportsADG004_WhenTwoTypesShareViewKey()
        {
            var result = GeneratorHarness.Run(@"
using Framework.Foundation.Initialization.Decorators.AutoView;
using Framework.Foundation.UI.Views;

namespace Game.Feature
{
    public partial class FirstCore
    {
        [AutoWindowAttribute(""shared_view"")] private FeatureWindowView _view;
    }

    public partial class SecondCore
    {
        [AutoWindowAttribute(""shared_view"")] private FeatureWindowView _view;
    }

    public class FeatureWindowView : MonoView
    {
    }
}");

            Assert.AreEqual(new[] { "ADG004", "ADG004" }, result.DiagnosticIds);
            Assert.That(result.GeneratorDiagnostics[0].GetMessage(), Does.Contain("FirstCore, SecondCore"));

            // Генерация не прерывается: иначе к ошибке о ключе добавились бы каскадные
            // CS-ошибки об отсутствующем IAutoViewHost.
            Assert.AreEqual(2, result.GeneratedSources.Count);
            Assert.IsEmpty(result.CompilationErrors);
        }
